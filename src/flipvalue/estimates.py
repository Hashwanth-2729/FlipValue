"""FlipValue modelled estimates: rough prices for every catalogued phone, generated from price bands.

They are not market observations. `data/estimates/price_bands.csv` holds, per model and base storage variant, the
launch price and current new / refurbished / used price ranges (owner-supplied ranges and figures derived from the
manual price checks; the `basis` column says which). From that file this module writes three labelled sources:

* `flipvalue-estimates` (source type `estimate`): resale prices per grade, one set per month since release. The
  engine uses only the latest month, and only when no completed sales or listings exist; the trends page draws all
  months as the modelled depreciation curve.
* `flipvalue-estimates-buyback` (`estimate_buyback`): dealer buyback prices per grade for the latest month.
* `flipvalue-store-estimates` (`estimate`): one estimated offer per store and condition for the price comparison.
  No links, never alerts, never price history, and shown with an "Estimate" label.

Model (docs/VALUATION_METHODOLOGY.md, "Modelled estimates"):
* grade prices from the used band [L, H]: excellent H, good (L+H)/2, fair L, poor 0.75 L, faulty 0.45 L;
* buyback = 70% of the private-sale price of the same grade;
* larger storage: +8% per step for used/refurbished, +10% per step for new;
* history: exponential decline from 80% of the launch price in the release month to today's price.

Regenerating replaces every row of these sources (idempotent); `release` does it on each deploy.
"""

from __future__ import annotations

import csv
import hashlib
import math
from dataclasses import dataclass
from datetime import date, datetime
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

from sqlalchemy import delete, insert, select
from sqlalchemy.orm import Session

from flipvalue import catalogue
from flipvalue.config import ROOT
from flipvalue.db.models import DeviceModel, IngestionJob, MarketplaceOffer, Observation, PriceAlert, utcnow
from flipvalue.ingestion.sources import SourceSpec, register_source
from flipvalue.marketplace.providers import RawOffer
from flipvalue.marketplace.service import store_offers

PRICE_BANDS = ROOT / "data" / "estimates" / "price_bands.csv"
COLUMNS = ("model_id", "launch_price", "new_low", "new_high", "refurb_low", "refurb_high", "used_low", "used_high",
           "basis")
ESTIMATE_TYPES = ("estimate", "estimate_buyback")

_TERMS = ("Not market data. Modelled by FlipValue from launch prices and approximate current price ranges "
          "(data/estimates/price_bands.csv); always labelled as an estimate on the website and in the API.")
RESALE = SourceSpec(
    id="flipvalue-estimates", name="FlipValue estimates (modelled)", source_type="estimate",
    collection_method="Generated by `flipvalue load-estimates` from data/estimates/price_bands.csv", markets="IN",
    terms_note=_TERMS, verified=False)
BUYBACK = SourceSpec(
    id="flipvalue-estimates-buyback", name="FlipValue buyback estimates (modelled)", source_type="estimate_buyback",
    collection_method="Generated by `flipvalue load-estimates`: 70% of the modelled private-sale price",
    markets="IN", terms_note=_TERMS, verified=False)
STORES = SourceSpec(
    id="flipvalue-store-estimates", name="FlipValue store price estimates", source_type="estimate",
    collection_method="Generated by `flipvalue load-estimates`: a price per store inside the estimated range",
    markets="IN", terms_note=_TERMS + " Store names show where such prices are typically found; they are not "
                                      "listings retrieved from those stores.", verified=False)

GRADE_FROM_USED = {"excellent": (0.0, 1.0), "good": (0.5, 0.5), "fair": (1.0, 0.0), "poor": (0.75, 0.0),
                   "faulty": (0.45, 0.0)}  # grade price = a * used_low + b * used_high
BUYBACK_SHARE = Decimal("0.70")
STEP_USED, STEP_NEW = Decimal("0.08"), Decimal("0.10")
LAUNCH_RESALE_SHARE = 0.80   # a used phone in the release month, relative to the launch price
SPREAD = (Decimal("0.94"), Decimal("1"), Decimal("1.06"))   # three points per month: the estimate and its range
BRAND_STORE = {"Apple": "Apple Store", "Samsung": "Samsung Shop", "Google": "Google Store",
               "OnePlus": "OnePlus Store", "Nothing": "Nothing Store", "Xiaomi": "Mi Store",
               "Motorola": "Motorola Store", "Vivo": "Vivo Store"}
NEW_STORES = (("Amazon", "marketplace_seller"), ("Flipkart", "marketplace_seller"), ("Croma", "retailer"),
              ("Reliance Digital", "retailer"))
REFURB_STORES = ("Cashify", "Amazon Renewed", "Budli", "Controlz")
USED_STORES = ("OLX", "Quikr", "Facebook Marketplace")
BUYBACK_STORES = ("Cashify", "Budli")


class EstimateError(ValueError):
    pass


@dataclass(frozen=True)
class Band:
    model_id: str
    launch: Decimal
    new: tuple[Decimal, Decimal] | None
    refurb: tuple[Decimal, Decimal]
    used: tuple[Decimal, Decimal]
    basis: str


def _pair(row: dict[str, str], lo: str, hi: str) -> tuple[Decimal, Decimal] | None:
    if not row[lo] and not row[hi]:
        return None
    low, high = Decimal(row[lo]), Decimal(row[hi])
    if not 0 < low <= high:
        raise EstimateError(f"{lo} must be > 0 and <= {hi}")
    return low, high


def read_bands(path: Path = PRICE_BANDS) -> list[Band]:
    with path.open(newline="", encoding="utf-8-sig") as fh:
        reader = csv.DictReader(fh)
        if tuple(reader.fieldnames or ()) != COLUMNS:
            raise EstimateError(f"{path.name}: header must be {','.join(COLUMNS)}")
        bands = []
        for line, row in enumerate(reader, start=2):
            try:
                refurb, used = _pair(row, "refurb_low", "refurb_high"), _pair(row, "used_low", "used_high")
                if refurb is None or used is None:
                    raise EstimateError("refurbished and used ranges are required")
                bands.append(Band(row["model_id"], Decimal(row["launch_price"]), _pair(row, "new_low", "new_high"),
                                  refurb, used, row["basis"]))
            except (EstimateError, ArithmeticError) as exc:
                raise EstimateError(f"{path.name}:{line}: {exc}") from exc
    return bands


def _round(value: Decimal, step: int, minus: int = 0) -> Decimal:
    return (value / step).quantize(Decimal(1), rounding=ROUND_HALF_UP) * step - minus


def _fraction(*key: object) -> Decimal:
    """A stable position in [0, 1] for a store's price inside a range: same inputs, same price."""
    digest = hashlib.sha256("|".join(map(str, key)).encode()).hexdigest()
    return Decimal(int(digest[:8], 16)) / Decimal(0xFFFFFFFF)


def _months(start: date, end: date) -> list[date]:
    """First days of the months from the first one on or after `start` up to `end`."""
    month = start if start.day == 1 else date(start.year + start.month // 12, start.month % 12 + 1, 1)
    out = []
    while month <= end:
        out.append(month)
        month = date(month.year + month.month // 12, month.month % 12 + 1, 1)
    return out


def grade_prices(band: Band, factor: Decimal) -> dict[str, Decimal]:
    low, high = band.used
    return {g: (Decimal(str(a)) * low + Decimal(str(b)) * high) * factor for g, (a, b) in GRADE_FROM_USED.items()}


def _history(launch: Decimal, now_price: Decimal, good_now: Decimal, months: list[date]) -> list[tuple[date, Decimal]]:
    """Monthly prices from LAUNCH_RESALE_SHARE of the launch price (scaled to this grade) down to today's price."""
    start = float(launch) * LAUNCH_RESALE_SHARE * float(now_price / good_now)
    end = float(now_price)
    if start < end:  # never model a phone gaining value
        start = end
    n = len(months) - 1
    out = []
    for i, month in enumerate(months):
        t = i / n if n else 1.0
        wiggle = 1 + 0.012 * math.sin(i * 1.7) * (1 - t)  # small, fading month-to-month variation
        out.append((month, Decimal(str(start * (end / start) ** t * wiggle))))
    return out


def _observation_rows(source_id: str, job_id: int, model_id: str, storage: int, grade: str,
                      points: list[tuple[date, Decimal]], collected: datetime) -> list[dict]:
    rows = []
    for month, center in points:
        for i, k in enumerate(SPREAD):
            price = _round(center * k, 10)
            key = hashlib.sha256(f"{source_id}|{model_id}|{storage}|{grade}|{month}|{i}".encode()).hexdigest()
            rows.append({"source_id": source_id, "job_id": job_id, "model_id": model_id, "storage_gb": storage,
                         "region": "IN", "currency": "INR", "grade": grade, "price": price, "observed_at": month,
                         "collected_at": collected, "external_ref": None, "dedup_key": key, "is_mock": False})
    return rows


def _store_offers(model: DeviceModel, storage: int, band: Band, steps: int) -> list[tuple[str, RawOffer]]:
    used_f, new_f = 1 + STEP_USED * steps, 1 + STEP_NEW * steps
    size = f"{storage // 1024} TB" if storage >= 1024 else f"{storage} GB"
    name = f"{model.manufacturer} {model.name} ({size})"
    offers: list[tuple[str, RawOffer]] = []

    def add(store: str, condition: str, price_type: str, seller_type: str, price: Decimal, suffix: str = "",
            mrp: Decimal | None = None) -> None:
        ref = f"estimate-{model.id}-{storage}-{condition}-{price_type}-{store}".lower().replace(" ", "-")
        offers.append((ref, RawOffer(
            title=name + suffix, price=price, currency="INR", condition=condition, price_type=price_type,
            provider_product_id=ref, brand=model.manufacturer, mrp=mrp, seller=store, seller_type=seller_type,
            storage_gb=storage, raw={"estimate": True, "basis": band.basis})))

    def within(lo: Decimal, hi: Decimal, f: Decimal, *key: object) -> Decimal:
        return (lo + (hi - lo) * _fraction(model.id, storage, *key)) * f

    if band.new:
        mrp = _round(band.launch * new_f, 100, 1)
        for store, seller_type in NEW_STORES:
            price = min(_round(within(*band.new, new_f, store), 500, 1), mrp)
            add(store, "new", "new_retail", seller_type, price, mrp=mrp)
        add(BRAND_STORE.get(model.manufacturer, f"{model.manufacturer} store"), "new", "new_retail", "manufacturer",
            min(_round(band.new[1] * new_f, 500, 1), mrp), mrp=mrp)
    for store in REFURB_STORES:
        add(store, "refurbished", "refurbished_retail", "refurbisher",
            _round(within(*band.refurb, used_f, store), 500, 1), " - Refurbished")
    for store in USED_STORES:
        add(store, "used", "used_listing", "marketplace_seller", _round(within(*band.used, used_f, store), 500),
            " - Used, typical condition")
    good = grade_prices(band, used_f)["good"] * BUYBACK_SHARE
    for store in BUYBACK_STORES:
        price = good * (Decimal("0.95") + Decimal("0.10") * _fraction(model.id, storage, store, "buyback"))
        add(store, "used", "buyback_quote", "dealer", _round(price, 10), " - buyback, good condition")
    return offers


def load_estimates(session: Session, today: date | None = None, path: Path = PRICE_BANDS) -> dict[str, int]:
    """Replace all modelled estimates. Returns row counts. Unknown model ids in the file are an error."""
    today = today or date.today()
    bands = read_bands(path)
    sources = {spec.id: register_source(session, spec) for spec in (RESALE, BUYBACK, STORES)}
    session.execute(delete(Observation).where(Observation.source_id.in_((RESALE.id, BUYBACK.id))))
    old_offers = select(MarketplaceOffer.id).where(MarketplaceOffer.source_id == STORES.id)
    session.execute(delete(PriceAlert).where(PriceAlert.offer_id.in_(old_offers)))
    session.execute(delete(MarketplaceOffer).where(MarketplaceOffer.source_id == STORES.id))
    jobs = {}
    for source_id in sources:
        jobs[source_id] = IngestionJob(source_id=source_id, status="running", triggered_by="load-estimates",
                                       accepted=0, rejected=0, duplicates=0)
        session.add(jobs[source_id])
    session.flush()

    collected = utcnow()
    resale_rows: list[dict] = []
    buyback_rows: list[dict] = []
    offer_count = 0
    current_month = date(today.year, today.month, 1)
    for band in bands:
        model = session.get(DeviceModel, band.model_id)
        if model is None:
            raise EstimateError(f"price_bands.csv: {band.model_id} is not in the catalogue")
        released = model.release_date or date(today.year - 2, today.month, 1)
        months = _months(released, today) or [current_month]
        for steps, storage in enumerate(catalogue.variants(session, model.id)):
            factor = 1 + STEP_USED * steps
            prices = grade_prices(band, factor)
            for grade, price in prices.items():
                launch = band.launch * (1 + STEP_NEW * steps)
                resale_rows += _observation_rows(RESALE.id, jobs[RESALE.id].id, model.id, storage, grade,
                                                 _history(launch, price, prices["good"], months), collected)
                buyback_rows += _observation_rows(BUYBACK.id, jobs[BUYBACK.id].id, model.id, storage, grade,
                                                  [(current_month, price * BUYBACK_SHARE)], collected)
            stored = store_offers(session, sources[STORES.id], jobs[STORES.id],
                                  _store_offers(model, storage, band, steps), "IN", collected, model, storage)
            offer_count += len(stored)
    for rows in (resale_rows, buyback_rows):
        for i in range(0, len(rows), 2000):
            session.execute(insert(Observation), rows[i:i + 2000])
    jobs[RESALE.id].accepted, jobs[BUYBACK.id].accepted = len(resale_rows), len(buyback_rows)
    for job in jobs.values():
        job.status, job.finished_at = "succeeded", utcnow()
    session.flush()
    if jobs[STORES.id].rejected:
        raise EstimateError(f"{jobs[STORES.id].rejected} estimated store offers did not match their model")
    return {"models": len(bands), "resale_observations": len(resale_rows),
            "buyback_observations": len(buyback_rows), "store_offers": offer_count}
