"""Source registry. Every observation belongs to exactly one registered source."""

from __future__ import annotations

from dataclasses import dataclass

from sqlalchemy.orm import Session

from flipvalue.config import REGION_CURRENCY
from flipvalue.db.models import Source

SOURCE_TYPES = (
    "completed_sale",       # verified sold price
    "listing",              # asking price, not a sale
    "dealer_offer",         # buyer/dealer offer to a seller
    "trade_in",             # trade-in credit offered by a retailer/manufacturer
    "refurbished_retail",   # price a refurbisher charges for a refurbished unit
    "new_retail",           # retailer/marketplace selling price of a new unit (marketplace offers)
    "customer_quote",       # quote a customer received and submitted
    "synthetic",            # generated development data; never real
    "estimate",             # FlipValue modelled estimate (flipvalue.estimates); labelled, never presented as observed
    "estimate_buyback",     # modelled dealer buyback estimate
)


class SourceError(ValueError):
    pass


@dataclass(frozen=True)
class SourceSpec:
    id: str
    name: str
    source_type: str
    collection_method: str
    markets: str
    terms_note: str
    verified: bool
    url: str | None = None
    mock: bool = False  # development fixtures of a real source type (e.g. fixture marketplace offers)

    @property
    def is_mock(self) -> bool:
        return self.source_type == "synthetic" or self.mock


SYNTHETIC_DEV = SourceSpec(
    id="synthetic-dev",
    name="Synthetic development data (MOCK)",
    source_type="synthetic",
    collection_method="Generated by `flipvalue seed-mock` from data/mock/synthetic_spec.csv",
    markets="IN,US",
    terms_note="Not market data. For development and tests only; never used in production.",
    verified=False,
)


FIXTURE_OFFERS = SourceSpec(
    id="fixture-offers",
    name="Fixture marketplace offers (MOCK)",
    source_type="new_retail",
    collection_method="Generated by `flipvalue seed-mock` from data/mock/fixture_offers.csv",
    markets="IN",
    terms_note="Not market data: invented listings for development and tests only; no links; never used in "
               "production.",
    verified=False,
    mock=True,
)


def register_source(session: Session, spec: SourceSpec) -> Source:
    if not spec.id or len(spec.id) > 60 or not spec.id.replace("-", "").replace("_", "").isalnum():
        raise SourceError("source id must be 1-60 letters, digits, '-' or '_'")
    if spec.source_type not in SOURCE_TYPES:
        raise SourceError(f"source_type must be one of {', '.join(SOURCE_TYPES)}")
    markets = [m for m in spec.markets.split(",") if m]
    if not markets or any(m not in REGION_CURRENCY for m in markets):
        raise SourceError(f"markets must be a comma-separated subset of {', '.join(REGION_CURRENCY)}")
    if not spec.terms_note.strip():
        raise SourceError("terms_note is required: record the terms/permission under which data is collected")
    source = session.get(Source, spec.id) or Source(id=spec.id)
    source.name, source.source_type = spec.name, spec.source_type
    source.collection_method, source.url, source.markets = spec.collection_method, spec.url, spec.markets
    source.terms_note, source.verified, source.is_mock = spec.terms_note, spec.verified, spec.is_mock
    session.add(source)
    session.flush()
    return source
